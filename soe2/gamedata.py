"""The game-data library (1.38, Phase 2): every PoE 2 base type with its class, defense type and base group, every
modifier's trade-site stat, the pseudo totals, stackable currency names; plus reading any copied item's text.

gamedata.json is generated by tools/build_gamedata.py from Exiled Exchange 2's data (MIT license, see
THIRD_PARTY_NOTICES.txt). It ships inside the app and is copied into the data folder like modlists.json (versioned)."""
import json
import os
import re
import threading

from .config import APP_DIR, P, RESOURCE_DIR, load_json, save_json

_lock = threading.Lock()
_data = None
_by_text = {}          # normalized mod wording -> [(stat, negate)]
_bases_by_len = []     # base names, longest first (to find a base inside a magic item's name)
_class_by_text = {}    # "body armors" -> class id
_fallback = [None]     # 1.40: the window plugs in a lookup on the trade site's own stat list (for lines not in gamedata)
LEARNED_FILE = "learned_stats.json"     # wordings learned that way, kept between sessions
# lines that describe the whole item, not a mod
FLAG_LINES = {"Corrupted": "corrupted", "Twice Corrupted": "corrupted",       # 2.98.2: Vaal'd twice
              "Unidentified": "unidentified", "Mirrored": "mirrored", "Split": "split",
              "Fractured Item": "fractured", "Synthesised Item": "synthesised", "Sanctified": "sanctified",
              "Unmodifiable": "unmodifiable"}
SOURCES = ("fractured", "desecrated", "crafted")
# Owner decision A: the copied item's own flags, each searched as the trade site's Miscellaneous filter of the same
# name (trade.FLAG_FILTERS) - in the game's order
COPY_FLAGS = ("corrupted", "twice_corrupted", "mirrored", "fractured", "sanctified", "desecrated", "unrevealed",
              "crafted", "cultivated", "unidentified")
_SOURCE_TAG = re.compile(r"\((fractured|desecrated|crafted)\)\s*$", re.I)


def copy_flags(text):
    """A copied item's text -> the set of its flags (COPY_FLAGS): its flag lines (Corrupted, Twice Corrupted,
    Mirrored, Fractured Item, Sanctified, Unidentified), its mods' sources (a fractured / desecrated / crafted mod),
    an Unrevealed mod header, and a unique's Mutated mod (a Cultivated Vaal Unique)."""
    lines = [l.strip() for l in (text or "").replace("\r", "").split("\n")]
    rarity = next((l.split(":", 1)[1].strip() for l in lines if l.startswith("Rarity:")), "")
    out = set()
    for l in lines:
        f = FLAG_LINES.get(l)
        if f in COPY_FLAGS:
            out.add(f)
        if l == "Twice Corrupted":
            out.add("twice_corrupted")
        if l[:1] in ("{", "｛"):
            words = set(re.findall(r"[a-z]+", re.split(r'\s[—–-]\s|"', l.lower())[0]))
            out.update(w for w in SOURCES if w in words)
            if "unrevealed" in words:
                out.add("unrevealed")
            if "mutated" in words and rarity == "Unique":
                out.add("cultivated")
            continue
        t = _SOURCE_TAG.search(l)
        if t:
            out.add(t.group(1).lower())
    return out


FLAG_WORDS = {"twice_corrupted": "twice corrupted", "cultivated": "Cultivated Vaal Unique"}


def flag_words(item):
    """How a flagged item is searched, for the line under its price: ["mirrored only", ...] (Corrupted is said
    already: "corrupted only" / "uncorrupted only")."""
    return [FLAG_WORDS.get(f, f) + " only" for f in COPY_FLAGS if f in (item.get("flags") or ()) and f != "corrupted"]


def _find_file():
    for p in (P("gamedata.json"), os.path.join(RESOURCE_DIR, "gamedata.json"), os.path.join(APP_DIR, "gamedata.json")):
        if os.path.isfile(p):
            return p
    return None


def load():
    """The library, loaded once. Missing / broken file -> an empty library (callers check available())."""
    global _data
    with _lock:
        if _data is not None:
            return _data
        path = _find_file()
        try:
            with open(path, encoding="utf-8") as f:
                d = json.load(f)
        except Exception as e:
            d = {"classes": {}, "groups": {}, "bases": {}, "stats": [], "pseudo_rules": [], "currency": {},
                 "uniques": {}, "error": f"gamedata.json {'not found' if not path else 'could not be read'} ({e})"}
        for s in d["stats"]:
            for m in s.get("matchers", []):
                _by_text.setdefault(norm_mod(m["string"]), []).append((s, bool(m.get("negate"))))
        for key, e in (load_json(LEARNED_FILE, {}) or {}).items():     # learned from the trade site earlier
            if key not in _by_text:
                _by_text[key] = [({"ref": e["ref"], "trade": e["trade"], "better": 1, "learned": True}, bool(e.get("negate")))]
        _bases_by_len.extend(sorted(d["bases"], key=len, reverse=True))
        for cid, c in d["classes"].items():
            _class_by_text[c["name"].lower()] = cid
        _class_by_text.update({"life flasks": "flask", "mana flasks": "flask", "foci": "focus", "warstaves": "quarterstaff"})
        _data = d
        return d


def available():
    return bool(load()["bases"])


def info():
    d = load()
    return {"bases": len(d["bases"]), "groups": len(d["groups"]), "classes": len(d["classes"]), "stats": len(d["stats"]),
            "version": d.get("version"), "generated": d.get("generated"), "source": d.get("source", {}),
            "error": d.get("error")}


