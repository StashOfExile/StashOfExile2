# 2.121.0 (items pass, feedback: unknown items were still an issue): gamedata.json is built from
# Exiled Exchange 2's data, which can be a patch behind. The trade site's own item list (every base type and unique
# it knows - downloaded once a day, like the mod list: engine._load_items) fills the gaps: a base or unique the game
# data doesn't know yet is still read, and a unique name the trade site doesn't know is never sent to it.
TRADE_ITEMS = {"bases": set(), "uniques": {}, "by_len": [], "loaded": False}
TRADE_ITEMS_FILE = "trade_items.json"


def set_trade_items(data):
    """The trade site's /data/items answer -> TRADE_ITEMS. Never raises."""
    bases, uniques = set(), {}
    try:
        for group in (data or {}).get("result") or []:
            for e in group.get("entries") or []:
                t = str(e.get("type") or "").strip()
                if not t:
                    continue
                if (e.get("flags") or {}).get("unique") and e.get("name"):
                    uniques.setdefault(str(e["name"]).strip(), []).append(t)
                else:
                    bases.add(t)
    except Exception:
        return False
    TRADE_ITEMS.update(bases=bases, uniques=uniques, loaded=bool(bases or uniques),
                       by_len=sorted((b for b in bases if b not in load()["bases"]), key=len, reverse=True))
    return TRADE_ITEMS["loaded"]


def load_trade_items():
    """At start: the cached list (if any) - the engine downloads a fresh one once a day."""
    if not TRADE_ITEMS["loaded"]:
        set_trade_items(load_json(TRADE_ITEMS_FILE, {}) or {})
    return TRADE_ITEMS["loaded"]


def trade_knows_unique(name):
    """True / False when the trade site's list is loaded, None when it isn't (then nobody can tell)."""
    if not TRADE_ITEMS["loaded"]:
        return None
    return (name or "").strip() in TRADE_ITEMS["uniques"]


def find_base(text):
    """The base type inside a name line: exact first, else the longest base name it contains (magic items carry
    affixes around the base: 'Sapphire Ring of the Whale'). 2.121.0: then the trade site's own list (a base newer
    than the game data)."""
    d = load()
    t = (text or "").strip()
    if t in d["bases"]:
        return t
    for b in _bases_by_len:
        if re.search(rf"(?<![A-Za-z']){re.escape(b)}(?![A-Za-z'])", t):
            return b
    if t in TRADE_ITEMS["bases"]:
        return t
    for b in TRADE_ITEMS["by_len"]:
        if re.search(rf"(?<![A-Za-z']){re.escape(b)}(?![A-Za-z'])", t):
            return b
    return None


_MARKUP = re.compile(r"\[([^\]|]*\|)?([^\]]*)\]")
_RANGE = re.compile(r"\((-?\d+(?:\.\d+)?)[-–](-?\d+(?:\.\d+)?)\)")
# 2.74.1: a roll shown by name in the advanced copy - Mageblood's "Legacy of Gold (Amethyst-Topaz)" - is a range, as
# "(10-20)" is: the line is "Legacy of Gold"
_WRANGE = re.compile(r"\s*\(([A-Za-z][A-Za-z' ]*)\s*[-–]\s*([A-Za-z][A-Za-z' ]*)\)")
_NUM = re.compile(r"[+-]?\d+(?:[.,]\d+)?")
_TAGS = re.compile(r"\s*\((implicit|rune|enchant|crafted|desecrated|fractured|augmented|unscalable value|sanctum)\)\s*$", re.I)


def norm_mod(text):
    """Mod wording with every number as '#', lower-case: '+52(40-59) to maximum Life' -> '# to maximum life'."""
    t = _MARKUP.sub(r"\2", text or "")
    t = _WRANGE.sub("", _RANGE.sub("", t))
    while _TAGS.search(t):
        t = _TAGS.sub("", t)
    t = _NUM.sub("#", t)
    t = t.replace("+#", "#")
    return re.sub(r"\s+", " ", t).strip().lower()


def set_fallback(fn):
    """fn(line) -> {"ref", "trade": {group: [ids]}, "negate"} from the trade site's stat list, or None."""
    _fallback[0] = fn


def stat_for(text, learn=True):
    """-> (stat entry, negate) for a mod line, or (None, False). A wording gamedata doesn't know is looked up on the
    trade site's own stat list (if the window plugged that in) and remembered in learned_stats.json."""
    load()
    key = norm_mod(text)
    hits = _by_text.get(key)
    if hits:
        return hits[0]
    if learn and _fallback[0]:
        try:
            got = _fallback[0](text)
        except Exception:
            got = None
        if got and got.get("trade"):
            e = {"ref": got.get("ref") or key, "trade": got["trade"], "better": 1, "learned": True}
            _by_text[key] = [(e, bool(got.get("negate")))]
            with _lock:
                saved = load_json(LEARNED_FILE, {}) or {}
                saved[key] = {"ref": e["ref"], "trade": e["trade"], "negate": bool(got.get("negate"))}
                save_json(LEARNED_FILE, saved)
            return e, bool(got.get("negate"))
    return None, False


def numbers(text):
    """The values on a mod line (ranges in brackets removed), and the first range if the advanced copy shows one."""
    t = _MARKUP.sub(r"\2", text or "")
    rng = _RANGE.search(t)
    vals = [float(n.replace(",", "")) for n in _NUM.findall(_RANGE.sub("", t))]
    return vals, ((float(rng.group(1)), float(rng.group(2))) if rng else None)


def currency(name):
    return load()["currency"].get(name)


# ---------------------------------------------------------------- reading a copied item (any class)
PROP_RE = {
    "quality": re.compile(r"^Quality(?:\s*\([^)]*\))?:\s*\+?(\d+)%"),   # 2.105.0: "Quality (Caster Modifiers): +40%"
    "armour": re.compile(r"^Armour:\s*(\d+)"),
    "evasion": re.compile(r"^Evasion Rating:\s*(\d+)"),
    "energy_shield": re.compile(r"^Energy Shield:\s*(\d+)"),
    "ilvl": re.compile(r"^Item Level:\s*(\d+)"),
    "stack": re.compile(r"^Stack Size:\s*([\d,.\s]+)(?:/\s*([\d,.\s]+))?"),
}
CORRUPTION_HEADER = re.compile(r"^\{\s*(?:Corruption\s+)?Enhancement\b[^}]*\}\s*$", re.I)   # 2.105.0: "{ Enhancement }"
_BRACED = re.compile(r"^[\{｛].*[\}｝]\s*$")
_EMPTY_PARENS = re.compile(r"\(\s*\)")


def _clean_line(l):
    """A mod line as the stat lists word it: no "(Amethyst-Topaz)" range, no "— Unscalable Value", and (2.138.4)
    no empty "()" - the game prints "Allocates Overwhelm()" on a Megalomaniac."""
    l = _WRANGE.sub("", l)
    l = re.sub(r"\s+[—-]\s+Unscalable Value.*$", "", l)
    return _EMPTY_PARENS.sub("", l).strip()


MOD_HEADER = re.compile(r'^\{\s*(?P<kind>[A-Za-z ]+?)\s+Modifier(?:\s+"(?P<name>[^"]*)")?(?:\s*\(Tier:\s*(?P<tier>\d+)\))?')
# The words of a mod header that say what kind of mod it is ("{ Fractured Suffix Modifier ... }": suffix). Any other
# word ("Mutated", "Bonded", "Unrevealed" - the game adds new ones) is kept as a tag on the mod, never its kind: a mod
# whose kind was an unknown word was left out of the search.
MOD_KINDS = ("prefix", "suffix", "implicit", "unique", "enchant", "rune", "explicit")
KNOWN_HEADER_WORDS = set(MOD_KINDS) | set(SOURCES) | {"essence", "corruption", "enhancement", "modifier", "tier"}
_HEADERS_LOGGED = set()


def header_words(words):
    """A mod header's words (lower-case) -> (kind or None, source or None, the other words: tags)."""
    kind = next((w for w in words if w in MOD_KINDS), None)
    source = next((w for w in words if w in SOURCES), None)
    return kind, source, [w for w in words if w != kind and w != source]


def log_header(line, words):
    """A header word the app doesn't know: once per session, a line in unmatched_mods.txt (the data folder)."""
    new = [w for w in words if w not in KNOWN_HEADER_WORDS and w not in _HEADERS_LOGGED]
    if not new:
        return
    _HEADERS_LOGGED.update(new)
    try:
        with open(P("unmatched_mods.txt"), "a", encoding="utf-8") as f:
            f.write(f"{line}\t| mod header word not known yet: {', '.join(new)} (the mod is read as usual)\n")
    except Exception:
        from . import buglog
        buglog.caught()


def _lore(sec):
    """A section of plain words: no mod header, no number, no line the stat lists know."""
    sec = [l for l in sec if l not in FLAG_LINES and not l.startswith(("Note:", "Place into", "Right click"))]
    if not sec:
        return None
    # 2.138.4 (feedback: a Megalomaniac priced by name only - its "{ Enhancement }" / "Allocates Overwhelm()" lines
    # were read as lore): any { ... } header line means the section holds mods
    return not any(MOD_HEADER.match(l) or _NUM.search(l) or _BRACED.match(l) for l in sec) and \
        not any(stat_for(_clean_line(l))[0] for l in sec)


def flavour_sections(sections, mods_from, unique=False):
    """2.74.1: the flavor text (a unique's lore lines) -> the indices of its sections. Any item: the last section
    with text, if it's plain words. 2.74.4: a unique - every plain-words section (The Brass Dome's "The turtle's
    shell one day becomes its tomb." was read as a mod: a section after it)."""
    out = set()
    if unique:
        return {i for i in range(mods_from, len(sections)) if _lore(sections[i])}
    for i in range(len(sections) - 1, mods_from - 1, -1):
        lo = _lore(sections[i])
        if lo is None:
            continue                                         # (Corrupted, a price note: look further up)
        if lo:
            out.add(i)
        break
    return out


def flavour_section(sections, mods_from):
    """(2.74.1's one-section form, kept for callers.)"""
    got = flavour_sections(sections, mods_from)
    return min(got) if got else None


# 2.15x: why a copy key press didn't give the price checker an item - worked out from the one read's text only
COPY_MISSED = "The copy didn't land - press the key again."
COPY_NOT_ITEM = "That copy isn't an item - point at an item in the game and press the key again."
COPY_NOT_ENGLISH = "That copy is from a game that isn't in English - the price checker reads English copies only."
_LABEL_LINE = re.compile(r"^[^\W\d_][^:\n]{1,40}:\s*\S")


def plain_minus(text):
    """A minus sign written as the Unicode one ("−10%") -> "-10%": numbers and stat wordings read the same."""
    return (text or "").replace("\u2212", "-")


def copy_problem(text):
    """A copy that isn't an English item -> the one line that says why (empty, another language, not an item);
    None for an English item copy."""
    t = (text or "").replace("\r", "").strip()
    if not t:
        return COPY_MISSED
    if t.startswith("Item Class:"):
        return None
    lines = [l.strip() for l in t.split("\n") if l.strip()]
    if any(l.startswith("--------") for l in lines) and _LABEL_LINE.match(lines[0]) and len(lines) >= 3:
        return COPY_NOT_ENGLISH                     # an item's shape (a "Label: value" line, then ------ lines)
    return COPY_NOT_ITEM


def unpriced_why(g):
    """A read_item() result the price checker doesn't price -> why, in a few words."""
    if g.get("stack") is not None:
        return "stackable items are counted on the Wealth window, not price-checked here"
    if g.get("rarity") == "Normal" and g.get("class") in ("jewel", "waystone"):
        return "a normal (white) one has no mods to price"
    if g.get("class") in ("tablet", "jewel") and g.get("rarity") in ("Magic", "Rare"):
        return "its name line wasn't recognized (the copied text is saved in unpriced_items.txt in the data folder)"
    if not g.get("class"):
        return "the price checker doesn't price this kind of item yet"
    if not g.get("base"):
        return "its base type isn't in the library"
    return "the price checker doesn't price this kind of item yet"


def unpriced_line(g):
    """-> "Rings: not priced - <why>." (the one line the status bar and the card show)."""
    cls = classes().get(g.get("class") or "", {}).get("name") or g.get("class_text") or "This item"
    return f"{cls}: not priced - {unpriced_why(g)}."


def read_item(text):
    """Everything the price checker needs from a copied item (Ctrl+C or Ctrl+Alt+C), whatever its class.
    -> dict, or None if the text isn't an item."""
    lines = [l.rstrip() for l in plain_minus(text).replace("\r", "").split("\n")]
    if not lines or not lines[0].startswith("Item Class:"):
        return None
    sections, cur = [], []
    for l in lines:
        if l.startswith("--------"):
            if cur:
                sections.append(cur)
            cur = []
        elif l.strip():
            cur.append(l.strip())
    if cur:
        sections.append(cur)
    head = sections[0]
    cls_text = head[0].split(":", 1)[1].strip()
    rarity = next((l.split(":", 1)[1].strip() for l in head if l.startswith("Rarity:")), "")
    names = [l for l in head[1:] if not l.startswith("Rarity:")]
    item = {"class_text": cls_text, "rarity": rarity, "name": "", "base": None, "group": None, "class": None,
            "defence": None, "quality": 0, "sockets": 0, "socket_types": "", "ilvl": None, "corrupted": False,
            "flags": [], "props": {},
            "stack": None, "mods": [], "unknown": []}
    if rarity in ("Rare", "Unique") and len(names) >= 2:
        item["name"], base_line = names[0], names[1]
    else:
        base_line = names[0] if names else ""
        item["name"] = base_line
    item["base"] = find_base(base_line) or find_base(" ".join(names))
    b = base(item["base"]) if item["base"] else None
    item["class"] = (b or {}).get("class") or class_from_text(cls_text)
    if b:
        item["group"], item["defence"] = b.get("group"), b.get("defence")
    mods_from = None
    for i, sec in enumerate(sections[1:], 1):
        for l in sec:
            for key, rx in PROP_RE.items():
                m = rx.match(l)
                if m:
                    if key == "stack":
                        item["stack"] = int(re.sub(r"[^\d]", "", m.group(1)) or 0)
                        if m.group(2):
                            item["stack_max"] = int(re.sub(r"[^\d]", "", m.group(2)) or 0)
                    else:
                        item["props"][key] = int(m.group(1))
            if l.startswith("Sockets:"):
                letters = re.findall(r"[A-Za-z]", l.split(":", 1)[1])
                item["sockets"], item["socket_types"] = len(letters), "".join(letters).upper()   # S = socket, J = jewel
            if l in FLAG_LINES and FLAG_LINES[l] not in item["flags"]:
                item["flags"].append(FLAG_LINES[l])
            if l == "Twice Corrupted" and "twice_corrupted" not in item["flags"]:
                item["flags"].append("twice_corrupted")
            if l.startswith("Item Level:"):
                mods_from = i + 1
    item["corrupted"] = "corrupted" in item["flags"]
    item["quality"] = item["props"].get("quality", 0)
    item["ilvl"] = item["props"].get("ilvl")
    if mods_from is None:
        mods_from = len(sections)
    flavour = flavour_sections(sections, mods_from, unique=rarity == "Unique")    # 2.74.1: never read as mods
    item["flavour"] = [l for i in sorted(flavour) for l in sections[i]]
    for si, sec in enumerate(sections[mods_from:], mods_from):
        if si in flavour:
            continue
        kind, tier, mname, source, tags = None, None, None, None, []
        for l in sec:
            if CORRUPTION_HEADER.match(l):                    # 2.98.2: "{ Corruption Enhancement — Mana }" - what a
                kind, tier, mname, source, tags = "enchant", None, None, None, []    # Vaal Orb added (an enchantment)
                continue
            h = MOD_HEADER.match(l)
            if h:                                             # advanced copy: "{ Fractured Suffix Modifier "of X" (Tier: 1) }"
                words = h.group("kind").strip().lower().split()
                kind, source, tags = header_words(words)      # (no kind word: the line's own tag decides, else explicit)
                log_header(l, tags)
                tier = int(h.group("tier")) if h.group("tier") else None
                mname = h.group("name")
                continue
            if re.match(r"^[\{｛].*[\}｝]\s*$", l.strip()):         # 2.121.0 (unmatched_mods.txt: "{ Enhancement }"
                if "enhancement" in l.lower():               # read as a mod): any { ... } line is a header, never a mod
                    kind, tier, mname, source, tags = "enchant", None, None, None, []
                else:                                        # a header we don't know: the lines under it are read on
                    words = [w for w in re.findall(r"[a-z]+", re.split(r"\s[—–-]\s", l)[0].lower())   # their own (not
                             if w not in ("modifier", "tier")]                            # as part of the mod above it)
                    kind, source, tags = header_words(words)
                    tier, mname = None, None
                    log_header(l, tags)
                continue
            if l in FLAG_LINES or l.startswith(("Note:", "Place into", "Right click")):
                continue
            # 2.74.1: "Legacy of Gold (Amethyst-Topaz)" -> "Legacy of Gold"; 2.105.0: "Allocates Paragon — Unscalable
            # Value"; 2.138.4: "Allocates Overwhelm()" (see _clean_line)
            l = _clean_line(l)
            tag = _TAGS.search(l)
            tagged = tag.group(1).lower() if tag else None
            k = kind or (tagged if tagged in ("implicit", "rune", "enchant") else "explicit")
            src = source or (tagged if tagged in SOURCES else None)
            stat, neg = stat_for(l)
            vals, rng = numbers(l)
            if neg:
                vals = [-v for v in vals]
            # trade: every id this wording has (any of them matches)
            group_key = src or (k if k in ("implicit", "rune", "enchant") else "explicit")
            m = {"text": l, "kind": k, "source": src, "tier": tier, "affix": mname, "values": vals, "range": rng,
                 "stat": stat["ref"] if stat else None, "local": bool(stat and stat.get("local")),
                 "learned": bool(stat and stat.get("learned")),
                 "trade": list(stat["trade"].get(group_key) or stat["trade"].get("explicit")
                               or next(iter(stat["trade"].values()), [])) if stat else []}
            if tags:                                          # a header word that isn't the mod's kind ("Mutated")
                m["header"] = list(tags)
            item["mods"].append(m)
            if not stat:
                item["unknown"].append(l)
    return item
